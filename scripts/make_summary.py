"""Builds results/SUMMARY.md from the generated result files (no hand-typed numbers)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"


def read(p):
    return (R / p).read_text(encoding="utf-8")


def body(p):
    """A generated table file without its title line."""
    return read(p).split("\n", 1)[1].strip()


def evidence_table():
    lines = ["| Dataset | Domain | Model | Val event F1 | Best baseline (val) | Val Brier | Test event F1 | Test Brier |",
             "|---|---|---|---|---|---|---|---|"]
    for f in sorted((R / "evidence").glob("*__*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        b = d["best_baseline_val"]
        lines.append(f"| {d['dataset']} | {d['domain']} | {d['model_selected']} | {d['val']['event']['f1']:.3f} | "
                     f"{b['model']} {b['val_event_f1']:.3f} | {d['val']['brier']:.3f} | {d['test']['event']['f1']:.3f} | "
                     f"{d['test']['brier']:.3f} |")
    return "\n".join(lines)


def fusion_statement():
    d = json.loads(read("fusion/fusion_results.json"))
    sel = d["selected"]
    rows = {(r["dataset"], r["model"]): r for r in d["rows"]}

    def g(ds, m):
        r = rows[(ds, m)]["test"]
        return r["macro_f1"], r["any_alert"]["event"]["f1"], r["any_alert"]["false_alarms_per_day"]

    out = [f"Selected design: **{sel}** ({d['selection_reason']})."]
    for ds in ("scenarios", "battledim"):
        s, v = g(ds, sel), g(ds, "threshold voting (no fusion)")
        nt = g(ds, f"{sel} (no temporal)")
        verdict = "beats" if s[1] > v[1] else "does NOT beat"
        out.append(f"- `{ds}` test: {sel} macro-F1 {s[0]:.3f}, event F1 {s[1]:.3f}, {s[2]:.2f} false alarms/day. "
                   f"Simple threshold voting on the same evidence: macro-F1 {v[0]:.3f}, event F1 {v[1]:.3f}, "
                   f"{v[2]:.2f} false alarms/day. On event-level F1 the selected fusion {verdict} threshold voting. "
                   f"Without temporal features: macro-F1 {nt[0]:.3f}, event F1 {nt[1]:.3f}.")
    return "\n".join(out)


LIMITS = """- **No real field data with labels.** The infrastructure data (BattLeDIM) are simulated hydraulics with exact leak labels; quality data (USGS river stations) are real but unlabelled, so all quality events are injected.
- **Fusion is tested on semi-synthetic scenarios** (events injected into real/simulated backgrounds). Event shapes and sizes are assumptions (docs/scenarios.md); good scores show the method recovers those assumptions, not that it works on real incidents.
- **Mixed-origin nodes.** Scenario nodes pair BattLeDIM infrastructure series with Virginia river quality series; the 8 demo nodes are a fictional layout near Vellore.
- **Low-cost sensor caveats** (drift, fouling, noise, calibration) are not modelled beyond what the public series contain. TDS is a conductance proxy (0.64 x conductance).
- **Background contamination.** BattLeDIM always has concurrent leaks, which are unlabelled in the scenario backgrounds and drift the signals; the test period (late 2019) is more affected.
- **Rule-based priority.** The escalation rule is a documented heuristic, not validated against operator judgement.
- **Small test sets.** 60 scenario test events (12 per type) and 8 BattLeDIM test events; differences of a few points are within noise. No confidence intervals are computed.
- **Evidence modules are supervised** while the baselines are unsupervised; the comparison shows the value of labelled training, not a like-for-like detector contest.
- **No Docker run.** The MQTT/TimescaleDB path is implemented but was not exercised in this environment (fallback SQLite plus in-process bus was used)."""


def main():
    parts = ["# KAMI results summary", "",
             "Generated by `python scripts/make_summary.py` from files in `results/`. Simulated-hydraulics BattLeDIM results "
             "and semi-synthetic scenario results are always reported separately.", "",
             "## 1. Baselines (test)", "", body("tables/baselines.md"), "",
             "## 2. Evidence modules (calibrated)", "", evidence_table(), "",
             "Reliability curves: `results/figures/reliability_*.png`.", "",
             "## 3. Fusion and ablations (test)", "", fusion_statement(), "", body("tables/fusion_ablation.md"), "",
             "Confusion matrices: `results/tables/confusion_matrices.md`.", "",
             "## 4. Limitations", "", LIMITS, ""]
    (R / "SUMMARY.md").write_text("\n".join(parts), encoding="utf-8")
    print("wrote results/SUMMARY.md")


if __name__ == "__main__":
    main()
