import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { injectAndWait, open, PAGES, setPaused, THEMES } from "./helpers";

// axe-core on every page in both themes. Serious and critical findings fail the run unless the rule is listed in
// e2e/a11y_accepted.json with a reason (the same list is in docs/decisions.md). The report goes to results/a11y/.
// Output folder: results/ only when scripts/screenshots.py asks for it (KAMI_E2E_WRITE_RESULTS=1). A plain
// `npx playwright test` and the check scripts write to a scratch folder, so the stored files are never rewritten by accident.
const BASE = process.env.KAMI_E2E_OUT ?? (process.env.KAMI_E2E_WRITE_RESULTS === "1" ? path.resolve(process.cwd(), "..", "results") : path.join(os.tmpdir(), "kami_e2e_out"));
const OUT = path.resolve(BASE, "a11y");
const ACCEPTED: { id: string; reason: string }[] = JSON.parse(fs.readFileSync(path.resolve(process.cwd(), "e2e", "a11y_accepted.json"), "utf-8"));
const BLOCKING = ["serious", "critical"];

type Finding = { id: string; impact: string | null; help: string; helpUrl: string; nodes: number; targets: string[] };
const scans: { page: string; theme: string; url: string; passes: number; violations: Finding[] }[] = [];
let axeVersion = "";

test.describe.configure({ mode: "serial" });

test.beforeAll(async ({ request }) => {
  await injectAndWait(request); // the node page is scanned while it shows an alert
  await setPaused(request, true); // a still page: the same content for every scan
});

test.afterAll(async ({ request }) => {
  await setPaused(request, false);
  fs.mkdirSync(OUT, { recursive: true });
  const accepted = new Set(ACCEPTED.map((a) => a.id));
  const all = scans.flatMap((s) => s.violations.map((v) => ({ ...v, page: s.page, theme: s.theme })));
  const blocking = all.filter((v) => BLOCKING.includes(v.impact ?? ""));
  const report = {
    tool: `axe-core ${axeVersion} through @axe-core/playwright (Chromium, 1440x900)`,
    created_utc: new Date().toISOString(),
    rule_set: "axe default rules (WCAG 2.x A and AA plus best practices)",
    pages_scanned: scans.length,
    violations_total: all.length,
    serious_or_critical: blocking.length,
    serious_or_critical_unresolved: blocking.filter((v) => !accepted.has(v.id)).length,
    accepted_rules: ACCEPTED,
    scans,
  };
  fs.writeFileSync(path.join(OUT, "axe_report.json"), JSON.stringify(report, null, 1) + "\n");
  const rows = scans.map((s) => {
    const by = (impact: string) => s.violations.filter((v) => v.impact === impact).length;
    const ids = s.violations.map((v) => `${v.id} (${v.impact}, ${v.nodes})`).join("; ") || "none";
    return `| ${s.page} | ${s.theme} | ${s.passes} | ${by("critical")} | ${by("serious")} | ${by("moderate")} | ${by("minor")} | ${ids} |`;
  });
  const md = [
    "# Accessibility check (axe-core)",
    "",
    `Generated by \`frontend/e2e/a11y.spec.ts\` (${report.tool}), ${report.created_utc}. Rule set: ${report.rule_set}.`,
    "An automated scan finds only part of all accessibility problems; it does not replace testing with a screen reader or keyboard.",
    "",
    `Pages scanned: ${report.pages_scanned}. Findings: ${report.violations_total}. Serious or critical: ${report.serious_or_critical}, of which not resolved and not accepted: ${report.serious_or_critical_unresolved}.`,
    "",
    "| Page | Theme | Rules passed | Critical | Serious | Moderate | Minor | Findings (impact, elements) |",
    "|---|---|---|---|---|---|---|---|",
    ...rows,
    "",
    "## Accepted findings (not fixed)",
    ...(ACCEPTED.length ? ACCEPTED.map((a) => `- \`${a.id}\`: ${a.reason}`) : ["None."]),
    "",
  ];
  fs.writeFileSync(path.join(OUT, "axe_report.md"), md.join("\n"));
});

for (const theme of THEMES) {
  for (const pg of PAGES) {
    test(`axe: ${pg.key}, ${theme} theme`, async ({ page }) => {
      await open(page, pg.hash, theme);
      await pg.ready(page);
      await expect(page.locator("footer")).toContainText("Alerts: dry run");
      const result = await new AxeBuilder({ page }).analyze();
      axeVersion = result.testEngine.version;
      const violations = result.violations.map((v) => ({
        id: v.id, impact: v.impact ?? null, help: v.help, helpUrl: v.helpUrl, nodes: v.nodes.length,
        targets: v.nodes.slice(0, 5).map((n) => n.target.join(" ")),
      }));
      scans.push({ page: pg.key, theme, url: pg.hash, passes: result.passes.length, violations });
    });
  }
}

test("no serious or critical finding is left unresolved", () => {
  expect(scans.length).toBe(THEMES.length * PAGES.length);
  const accepted = new Set(ACCEPTED.map((a) => a.id));
  const left = scans.flatMap((s) => s.violations.filter((v) => BLOCKING.includes(v.impact ?? "") && !accepted.has(v.id))
    .map((v) => `${s.page}/${s.theme}: ${v.id} (${v.nodes}) -> ${v.targets[0]}`));
  expect(left).toEqual([]);
});

